from tqdm import tqdm
import os
import argparse
from LLM_caller import llm_call
from extractor import verilog_extractor
from glob import glob
from verilog_syntax_function_eval import evaluate
from datetime import datetime

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

benchmark_list = [
    "RTLLM",
    # "VGen",
    "VerilogEval"
]

file_patterns = {
    "RTLLM": {"prompt_pattern": "design_description.txt",
                "testbench_pattern": "testbench.v"},
    "VGen": {"prompt_pattern": "prompt*", 
                "testbench_pattern": "tb_*"},
    "VerilogEval": {"prompt_pattern": "*prompt.txt", 
                    "testbench_pattern": "*test.sv"}
}

top_instruction = {
    "RTLLM": "",
    "VGen": "Please act as a professional verilog designer. \n Implement the following module.\n",
    "VerilogEval": "Please act as a professional RTL designer.\n"
}

def get_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model_name", type=str, default="gpt-3.5-turbo")
    parser.add_argument("--model_path", type=str, default="")
    parser.add_argument("--model_type", type=str, default="",)
    parser.add_argument("--benchmark", type=str, default="RTLLM", help="Currently, there are four valid options: RTLLM, VGen, VerilogEval, all.")
    parser.add_argument("--api_key", type=str, default="sk-")
    parser.add_argument("--base_url", type=str, default="")
    parser.add_argument("--pass_at_n", type=int, default=5)  # pass@5
    parser.add_argument("--temp_outputfile", type=str, default="temp_output/test.vvp")
    parser.add_argument("--correctness_file", type=str, default=f"correctness/correctness_file{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt")
    parser.add_argument("--gen_only", action='store_true', help="If set, only generate code without evaluation")
    parser.add_argument("--eval_only", action='store_true', help="If set, only run evaluation without generating code")
    parser.add_argument("--prompt_type", type=str, default="1", help="When the benchmark is VGen, the prompt_type should be set")
    parser.add_argument("--no_overwrite", action='store_true', help="If set, the exitsing files will not be overwritten")
    parser.add_argument("--add_module_header", action='store_true', help="The add module header to the code generated by model")

    parser.add_argument("--temperature", type=float, default=0.1)
    parser.add_argument("--N", type=int, default=1)
    parser.add_argument("--max_len", type=int, default=4096)
    parser.add_argument("--tokenizer", type=str, default='Salesforce/codet5p-220m-bimodal')
    parser.add_argument("--num_seqs_per_iter", type=int, default=1)
    parser.add_argument("--num_beams", type=int, default=8)

    args = parser.parse_args()

    args.correctness_file=f"correctness/correctness_file_{args.model_type}_{args.pass_at_n}.txt"
    
    if args.gen_only and args.eval_only:
        raise ValueError("Cannot set both gen_only and eval_only")
    
    if not os.path.exists(os.path.dirname(args.temp_outputfile)):
        os.mkdir(os.path.dirname(args.temp_outputfile))
        
    if not os.path.exists(os.path.dirname(args.correctness_file)):
        os.mkdir(os.path.dirname(args.correctness_file))

    if (args.model_name=="local_model" or args.model_name=="codet5_200m") and args.model_path == "":
        print("Please add model_path when use local model!")
        exit()
    
    print(f"The model you choose is: {args.model_name}")
    if args.model_name=="local_model" or args.model_name=="codet5_200m":
        print(f"The path of the model is:\n{args.model_path}")
    
    return args

def get_file_content(file_path):
    with open(file_path, "r") as f:
        content = f.read()
    return content

def write_file(content, file_path):
    with open(file_path, "w") as f:
        f.write(content)
        
def append_file(content, file_path):
    with open(file_path, "a") as f:
        f.write(content)

############### a temp function to tackle the problem that the code generated by codet5 does not have module head
import re
def complement_module_name(text, design_dir, benchmark):
    ref_pattern = {
        "RTLLM": "verified*",
        "VGen": "answer*",
        "VerilogEval": "*ref.sv"
    }

    ref_path1 = glob(os.path.join(design_dir, ref_pattern[benchmark]))
    ref_path2 = glob(os.path.join(design_dir, file_patterns[benchmark]["prompt_pattern"]))
    if len(ref_path1):
        ref_path = ref_path1[0]
    elif len(ref_path2):
        ref_path = ref_path2[0]
    else:
        return text
    
    with open(ref_path, 'r') as f:
        content = f.read()
    pattern = r'module\s+[^\(\s]+\s*(?:#\s*\(.*\)){0,1}\s*\(.*?\);'
    verilog_code_extracted = re.findall(pattern, content, re.DOTALL)[0]
    if benchmark == "RTLLM":
        verilog_code_extracted = verilog_code_extracted.replace("verified_", "")
    elif benchmark == "VerilogEval":
        verilog_code_extracted = verilog_code_extracted.replace("RefModule", "TopModule")

    text = verilog_code_extracted + '\n' + text

    return text

def complement_module_name_with_benchmark_translated(text, design_dir, benchmark):

    prompt_path = glob(os.path.join(design_dir, file_patterns[benchmark]["prompt_pattern"]))
    if len(prompt_path):
        prompt_path = prompt_path[0]
    else:
        return text
    with open(prompt_path, 'r') as f:
        content = f.read()
    pattern = r'module\s+[^\(\s]+\s*(?:#\s*\(.*\)){0,1}\s*\(.*?\);'
    verilog_code_extracted = re.findall(pattern, content, re.DOTALL)[0]
    text = verilog_code_extracted + '\n' + text
    return text
